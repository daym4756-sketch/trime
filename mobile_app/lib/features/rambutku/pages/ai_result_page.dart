                                  decoration: BoxDecoration(
                                    color: TrimeColors.primaryNavy.withValues(alpha: 0.9),
                                    borderRadius: TrimeSpacing.radiusPill,
                                  ),
                                  child: Text(
                                    '${(r.matchScore * 100).round()}% Cocok',
