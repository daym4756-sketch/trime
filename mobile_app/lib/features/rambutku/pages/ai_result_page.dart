            children: [
              Expanded(
                child: _buildPhotoCard(
                  context,
                  label: 'BEFORE',
                  image: File(widget.imagePath),
                  caption: 'Foto asli kamu',
                ),
              ),
              const Padding(
                padding: EdgeInsets.symmetric(horizontal: TrimeSpacing.md),
                child: Icon(
                  Icons.arrow_forward_rounded,
                  size: 32,
                  color: TrimeColors.secondaryBlue,
                ),
              ),
              Expanded(
                child: _buildPhotoCard(
                  context,
