                                    ),
                                  ],
                                ),
                              ],
                            ),
                          ),
                        ],
                      ),
                    ),
                  ),
                );
              },
            ),
          ),
          const SizedBox(height: TrimeSpacing.xl),
          if (selectedRec != null) ...[
            _buildRecommendationDetailCard(selectedRec),
            const SizedBox(height: TrimeSpacing.lg),
            PrimaryButton(
              label: '💈 Book Kapster untuk gaya ini',
              prefixIcon: Icons.event_available_rounded,
              onPressed: () => _navigateBooking(selectedRec),
            ),
          ],
          const SizedBox(height: TrimeSpacing.xxl),
        ],
      ),
    );
  }

