        children: [
          Row(
            children: [
              Icon(icon, size: 14, color: TrimeColors.primaryNavy),
              const SizedBox(width: 4),
              Text(
                label,
                style: GoogleFonts.poppins(
                  fontSize: 11,
                  fontWeight: FontWeight.w500,
