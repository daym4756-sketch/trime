            Icons.arrow_back,
            color: Colors.white,
          ),
        ),
        title: const Text(
          'Rambutku',
          style: TextStyle(
            color: Colors.white,
          ),
        ),
        flexibleSpace: Container(
          decoration: const BoxDecoration(
            gradient: TrimeColors.rambutkuHeaderGradient,
          ),
        ),
