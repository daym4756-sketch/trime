  Widget _buildChipInfo({
    required IconData icon,
    required String label,
    required Color color,
  }) {
    return Container(
      padding: const EdgeInsets.symmetric(
        horizontal: 10,
        vertical: 6,
      ),
      decoration: BoxDecoration(
        color: color.withValues(alpha: 0.1),
        borderRadius: TrimeSpacing.radiusPill,
      ),
      child: Row(
        mainAxisSize: MainAxisSize.min,
        children: [
          Icon(icon, size: 14, color: color),
          const SizedBox(width: 4),
          Text(
            label,
            style: GoogleFonts.poppins(
              fontSize: 11,
              fontWeight: FontWeight.w700,
              color: color,
            ),
          ),
        ],
      ),
    );
  }

  Widget _buildPhotoCard(
    BuildContext context, {
    required String label,
    File? image,
    String? networkImage,
    IconData? fallbackIcon,
    required String caption,
  }) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Container(
          decoration: BoxDecoration(
            borderRadius: TrimeSpacing.radiusLg,
            color: TrimeColors.surfaceAlt,
            border: Border.all(
              color: TrimeColors.secondaryBlue.withValues(alpha: 0.2),
              width: 1,
            ),
          ),
          height: 220,
          child: ClipRRect(
            borderRadius: TrimeSpacing.radiusLg,
            child: Stack(
              fit: StackFit.expand,
              children: [
                if (image != null)
                  Image.file(image, fit: BoxFit.cover)
                else if (networkImage != null && networkImage.isNotEmpty)
                  Image.network(
                    networkImage,
                    fit: BoxFit.cover,
                    errorBuilder: (_, _, _) => Center(
                      child: Icon(
                        fallbackIcon ?? Icons.image,
                        size: 72,
                        color: TrimeColors.primaryNavy.withValues(alpha: 0.4),
                      ),
                    ),
                  )
                else if (fallbackIcon != null)
                  Center(
                    child: Icon(
                      fallbackIcon,
                      size: 72,
                      color: TrimeColors.primaryNavy.withValues(alpha: 0.4),
                    ),
                  ),
                Positioned(
                  top: 10,
                  left: 10,
                  child: BadgeExclusive(
                    text: label,
                    type: BadgeType.promo,
                  ),
                ),
              ],
            ),
          ),
        ),
        const SizedBox(height: 8),
        Text(
          caption,
          style: Theme.of(context).textTheme.titleSmall?.copyWith(
                fontWeight: FontWeight.w600,
                color: TrimeColors.primaryNavy,
              ),
        ),
      ],
    );
  }
