class AiResultPage extends StatefulWidget {
  final String faceShape;
  final String imagePath;
  final Map<String, dynamic>? detailedResult;

  const AiResultPage({
    super.key,
    required this.faceShape,
    required this.imagePath,
    this.detailedResult,
  });

  @override
  State<AiResultPage> createState() => _AiResultPageState();
}

class _AiResultPageState extends State<AiResultPage> {
  final NumberFormat _currencyFormatter = NumberFormat.currency(
    locale: 'id_ID',
    symbol: 'Rp ',
    decimalDigits: 0,
  );
  int _selectedRecommendationIdx = 0;

  String get _faceDetails {
    final r = widget.detailedResult;
    if (r != null) {
      return (r['face_details'] ?? r['faceDetails'] ?? '').toString();
    }
    return '';
  }

  String get _hairType {
    final r = widget.detailedResult;
    if (r != null) {
      return (r['hair_type'] ?? r['hairType'] ?? 'Normal').toString();
    }
    return 'Normal';
  }

  double get _confidence {
    final r = widget.detailedResult;
    if (r != null) {
      final c = r['confidence'];
      if (c is num) return c.toDouble();
    }
    return 0.82;
  }

  List<HairRecommendation> get _recommendations {
    final r = widget.detailedResult;
    if (r != null && r['recommendations'] is List) {
      try {
        return (r['recommendations'] as List<dynamic>)
            .map((e) => HairRecommendation.fromJson(
                  Map<String, dynamic>.from(e as Map),
                ))
            .toList();
      } catch (_) {}
    }
    return [];
  }

  Color _difficultyColor(String level) {
    switch (level.toLowerCase()) {
      case 'tinggi':
      case 'high':
        return TrimeColors.dangerRed;
      case 'sedang':
      case 'medium':
        return TrimeColors.warningOrange;
      case 'rendah':
      case 'low':
      default:
        return TrimeColors.successGreen;
    }
  }

  void _navigateBooking(HairRecommendation r) {
    Navigator.of(context).push(
      MaterialPageRoute(
        builder: (_) => BookingCalendarPage(
          initialKapster: const Kapster(
            nama: 'Ravi Blackbourne',
            rating: 5.0,
            spesialisasi: ['Classic Cut', 'Fade Master'],
            badgeType: 'exclusive',
            isReady: true,
            topRank: '#1 TOP Kapster',
            fotoUrl:
                'https://core-normal.traeapi.us/api/ide/v1/text_to_image?prompt=master+barber+elegant+suit+under+apron+studio+portrait&image_size=portrait_4_3',
          ),
        ),
      ),
    );
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(content: Text('Booking untuk gaya: ${r.styleName}')),
    );
  }

  @override
  Widget build(BuildContext context) {
